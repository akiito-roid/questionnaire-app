import streamlit as st

st.title("🎤 ライブ帰りの出発時間アンケート（9/23 山中湖発）")
st.write("山中湖からの出発時間の希望を教えてください。")
st.info(
    "⚠️ 9/23(祝・最終日)はUターンラッシュの渋滞が予想されるため、目安の到着時間は交通状況によって前後する可能性があります。"
)

# ユーザー名の入力
user_name = st.text_input("あなたの名前（ニックネーム可）")

# 出発時間の選択肢と目安の到着時間
options = {
    "15時出発（池袋・渋谷着: 17時頃の目安）": "17:00頃",
    "16時出発（池袋・渋谷着: 18時頃の目安）": "18:00頃",
    "17時出発（池袋・渋谷着: 19時頃の目安）": "19:00頃",
    "18時出発（池袋・渋谷着: 20時頃の目安）": "20:00頃",
    "その他・未定": "調整中",
}

if user_name:
  st.write(f"こんにちは、**{user_name}** さん！")
  choice = st.radio("山中湖からの出発時間を選んでね", list(options.keys()))

  if st.button("回答を送信する"):
    st.success(f"【送信完了】{user_name} さんは「{choice}」で登録しました！")
    st.balloons()
else:
  st.warning("まずは名前を入力してください。")
